<#
ZCode Dream Skin 2.0 appearance CLI.

This is the only door a helper process (the skin gallery, and later the tray) uses to
change appearance. It speaks in FILES, not in stdout: a bridge that decided success
from printed text would turn a garbled or truncated log line into "the skin applied".
Exactly two parameters are accepted, both absolute paths generated by the caller.
#>
[CmdletBinding()]
param(
  [string]$RequestFile = '',
  [string]$ResultFile = ''
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'common-windows.ps1')
. (Join-Path $PSScriptRoot 'theme-windows.ps1')
. (Join-Path $PSScriptRoot 'zcode-product.ps1')
. (Join-Path $PSScriptRoot 'zcode-theme-catalog.ps1')
. (Join-Path $PSScriptRoot 'zcode-appearance-preferences.ps1')
. (Join-Path $PSScriptRoot 'zcode-appearance-snapshots.ps1')
# The door composes the fourth skin, and the composition lives in the seeder the shipped
# presets use; without this line the action would resolve only inside a repository that
# happens to have dot-sourced the seed for another entry point.
. (Join-Path $PSScriptRoot 'zcode-preset-seed.ps1')
. (Join-Path $PSScriptRoot 'zcode-appearance-controller.ps1')
. (Join-Path $PSScriptRoot 'zcode-tray-text.ps1')

$MaxFileBytes = 65536
$ResultSchema = 'zcode-dream-skin-result/1'

function Write-Zds2Result {
  param([string]$Path, $Result)
  $payload = [pscustomobject]@{
    schemaVersion = $ResultSchema
    requestId     = [string]$Result.requestId
    ok            = [bool]$Result.ok
    status        = $Result.status
    data          = $Result.data
    errorCode     = $Result.errorCode
    message       = [string]$Result.message
    operationId   = $Result.operationId
  }
  $json = ConvertTo-Json $payload -Depth 10
  if ([System.Text.Encoding]::UTF8.GetByteCount($json) -gt $MaxFileBytes) {
    $json = ConvertTo-Json ([pscustomobject]@{
      schemaVersion = $ResultSchema; requestId = [string]$Result.requestId; ok = $false
      status = $Result.status; data = $null; errorCode = 'RESULT_TOO_LARGE'
      message = 'the appearance result exceeded its size limit'; operationId = $Result.operationId
    }) -Depth 6
  }
  $directory = Split-Path -Parent $Path
  $null = [System.IO.Directory]::CreateDirectory($directory)
  $temp = "$Path.tmp-$([guid]::NewGuid().ToString('N'))"
  try {
    [System.IO.File]::WriteAllText($temp, $json, [System.Text.UTF8Encoding]::new($false))
    Move-Item -LiteralPath $temp -Destination $Path -Force
  } finally {
    if (Test-Path -LiteralPath $temp) { Remove-Item -LiteralPath $temp -Force -ErrorAction SilentlyContinue }
  }
}

function Read-Zds2BoundedFile {
  param([string]$Path)
  if (-not [System.IO.Path]::IsPathRooted($Path)) { throw 'INVALID_REQUEST:PATH_NOT_ROOTED' }
  if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { throw 'INVALID_REQUEST:REQUEST_FILE_MISSING' }
  $item = Get-Item -LiteralPath $Path -Force
  if ($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint) { throw 'INVALID_REQUEST:REQUEST_FILE_REPARSE' }
  if ($item.Length -gt $MaxFileBytes) { throw 'INVALID_REQUEST:REQUEST_FILE_TOO_LARGE' }
  $bytes = [System.IO.File]::ReadAllBytes($Path)
  if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF) {
    throw 'INVALID_REQUEST:REQUEST_FILE_HAS_BOM'
  }
  return [System.Text.UTF8Encoding]::new($false).GetString($bytes)
}

function New-Zds2LiveEffects {
  <#
  The real machine boundaries. Each seam is closed over the state root and the script
  directory: a scriptblock that reads a local variable of its defining function at a
  later time would find it gone, and an empty -StateRoot would silently point at the
  default library instead of failing.

  Resume deliberately calls the existing restore function with a Reapply seam that
  runs the existing start FUNCTION: the previous generation shelled out to the start
  CLI here, and that child would come back for the root lock the parent still holds.

  Nothing in this block is exercised by an offline run; it only becomes evidence once
  a managed session exists, which is P2 and the installed-candidate acceptance.
  #>
  param([string]$StateRoot, $Dependencies = $null)
  $stateRootValue = $StateRoot
  $scriptRootValue = $PSScriptRoot
  # The defaults are the real machine boundaries: an offline test may replace one of
  # them, but shipping code never observes through a stub by accident.
  $defaultDependencies = [pscustomobject]@{
      InvokeVerifier = {
        param($Root, $ExpectedAppearance, $ReportPath)
        $null = & (Join-Path $scriptRootValue 'verify-zcode-dream-skin.ps1') -StateRoot $Root `
          -ExpectedAppearance $ExpectedAppearance -ReportPath $ReportPath 2>&1
        return [int]$LASTEXITCODE
      }.GetNewClosure()
      ReadReport = {
        param($Path)
        if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $null }
        try { return (Get-Content -LiteralPath $Path -Raw -Encoding UTF8 | ConvertFrom-Json) } catch { return $null }
      }
      ObserveSession = {
        param($Root)
        $state = Read-ZCodeDreamSkinState -StateRoot $Root
        if (-not $state) {
          return [pscustomobject]@{ proved = $false; reason = 'no managed session state exists'; state = $null }
        }
        if (-not (Get-Process -Id ([int]$state.rootPid) -ErrorAction SilentlyContinue)) {
          return [pscustomobject]@{ proved = $false; reason = 'the recorded root process is gone'; state = $state }
        }
        $listeners = @(Get-ZCodePortListenerRows -Port ([int]$state.port))
        if (@($listeners | Where-Object { [int]$_.OwningProcess -eq [int]$state.rootPid }).Count -eq 0) {
          return [pscustomobject]@{ proved = $false; reason = 'the recorded loopback port is not owned by the recorded root process'; state = $state }
        }
        return [pscustomobject]@{ proved = $true; reason = ''; state = $state }
      }
      NowUtc = { (Get-Date).ToUniversalTime() }
      # The restore/start primitives stay the old product functions; a test may place
      # its own boundary around them, never around the whole effects object.
      RestoreAppearance = {
        param($Mode, $Root, $Reapply)
        if ($Reapply) {
          return Invoke-ZCodeDreamSkinRestore -Mode $Mode -StateRoot $Root -Reapply $Reapply
        }
        return Invoke-ZCodeDreamSkinRestore -Mode $Mode -StateRoot $Root
      }
      StartAppearance = {
        param($Root, $ArtSourceFormat, $InitialAppearance)
        if ($InitialAppearance) {
          return Invoke-ZCodeDreamSkinStart -StateRoot $Root -ArtSourceFormat $ArtSourceFormat -InitialAppearance $InitialAppearance
        }
        return Invoke-ZCodeDreamSkinStart -StateRoot $Root -ArtSourceFormat $ArtSourceFormat
      }
      StopWatchers = {
        param($State, $Root)
        return Stop-ZCodeManagedWatch -State $State -StateRoot $Root `
          -InjectorPath (Join-Path $scriptRootValue 'injector.mjs') `
          -NodePath (Get-DreamSkinNodeRuntime -MinimumMajor 22).Path
      }.GetNewClosure()
    }
  if (-not $Dependencies) {
    $Dependencies = $defaultDependencies
  }
  else {
    # A partially supplied boundary object must not turn a missing member into a null
    # command: anything the caller did not provide stays the shipped implementation.
    foreach ($boundaryName in @($defaultDependencies.PSObject.Properties.Name)) {
      $provided = $Dependencies.PSObject.Properties[$boundaryName]
      if (-not $provided -or $null -eq $provided.Value) {
        $Dependencies | Add-Member -NotePropertyName $boundaryName -NotePropertyValue $defaultDependencies.$boundaryName -Force
      }
    }
  }
  # One verification ruler, used by the Verify seam and by the roll back, so a
  # "restored" claim always rests on the same live evidence. Nothing here trusts an
  # exit code alone, and no expected value is ever reported back as an observation.
  $runVerification = {
    param($ExpectedAppearance, $ExpectedRevision, $OperationId)
    $problems = @()
    $reportPath = Join-Path $stateRootValue ('verify-' + [string]$OperationId + '.json')
    $startedAt = & $Dependencies.NowUtc
    # Evidence of a previous reading must never satisfy this one: the file is taken
    # away first, so a verifier that wrote nothing is refused rather than honoured.
    if (Test-Path -LiteralPath $reportPath -PathType Leaf) { Remove-Item -LiteralPath $reportPath -Force }
    $exit = 1
    try { $exit = & $Dependencies.InvokeVerifier $stateRootValue $ExpectedAppearance $reportPath } catch {
      $problems += "the verifier could not run: $($_.Exception.Message)"
    }
    $report = & $Dependencies.ReadReport $reportPath
    if (-not $report) { $problems += 'this operation produced no verify report' }
    $observed = $null
    $recordedRevision = ''
    if ($report) {
      $observed = $report.verify
      if ([string]$report.mode -cne 'zcode-verify') { $problems += "the report is not a verify report: $($report.mode)" }
      $reportedAt = [datetime]::MinValue
      try { $reportedAt = ([datetime]$report.reportedAt).ToUniversalTime() } catch { $reportedAt = [datetime]::MinValue }
      if ($reportedAt -lt $startedAt.AddSeconds(-2)) { $problems += 'the report predates this call' }
      $observation = & $Dependencies.ObserveSession $stateRootValue
      if (-not $observation.proved) {
        $problems += "the session behind the report is not provable: $($observation.reason)"
      }
      else {
        $recordedRevision = [string]$observation.state.themeVersion
        $stateBrowserId = ''
        try { $stateBrowserId = Get-ZCodeDreamSkinBrowserId -State $observation.state } catch { $stateBrowserId = '' }
        if (-not $stateBrowserId -or [string]$report.browserId -cne $stateBrowserId) {
          $problems += 'the report belongs to a different browser than the live session'
        }
        if ([int]$report.port -ne [int]$observation.state.port) {
          $problems += "the report belongs to port $($report.port), not the session port $($observation.state.port)"
        }
      }
      if (@($report.errors).Count -gt 0) {
        $problems += "the verifier reported errors: $((@($report.errors) | Select-Object -First 2) -join '; ')"
      }
      if ($ExpectedAppearance -eq 'native') {
        foreach ($layer in @('styleCount', 'backgroundCount', 'overlayCount', 'taggedParts')) {
          if ([int]$observed.$layer -ne 0) { $problems += "the native reading still counts ${layer}=$($observed.$layer)" }
        }
        if ([string]$observed.mode) { $problems += "the native reading still carries a skin mode: $($observed.mode)" }
        # The renderer of a native window reports no revision at all. Anything else is
        # a skin still running, whatever the state file says about being paused.
        if ([string]$report.rendererRevision) {
          $problems += "the window still reports a skin revision: $((([string]$report.rendererRevision)))"
        }
        # A paused session legitimately keeps the revision it would resume to, so a
        # recorded value is not evidence against native: the window's own report is.
      }
      else {
        foreach ($layer in @('styleCount', 'backgroundCount', 'overlayCount')) {
          if ([int]$observed.$layer -ne 1) { $problems += "the theme reading counts ${layer}=$($observed.$layer), expected 1" }
        }
        if (-not [string]$observed.mode) { $problems += 'the theme reading carries no compatibility mode' }
        # Three values must agree: what the page says it runs, what the session
        # records, and what the caller expected. Any pair missing is a lie somewhere.
        if (-not [string]$report.rendererRevision) {
          $problems += 'the renderer reported no revision for a themed window'
        }
        elseif ($recordedRevision -and [string]$report.rendererRevision -cne $recordedRevision) {
          $problems += "the window runs revision $((([string]$report.rendererRevision))) but the session records $recordedRevision"
        }
        if ($ExpectedRevision -and $recordedRevision -cne [string]$ExpectedRevision) {
          $problems += "the live session records revision $recordedRevision, not $ExpectedRevision"
        }
      }
    }
    $confirmed = (($exit -eq 0) -and ($problems.Count -eq 0))
    $observedAppearance = 'pending'
    if ($observed) { $observedAppearance = if ([string]$observed.mode) { 'theme' } else { 'native' } }
    return [pscustomobject]@{
      confirmed        = $confirmed
      session          = $(if ($confirmed) { 'managed' } else { 'unknown' })
      appearance       = $observedAppearance
      themeId          = $null
      # The live reading, never the expectation: an unrevised native session reports
      # an empty revision rather than the last skin revision it replaced.
      revision         = $(if ($observedAppearance -eq 'theme') { $recordedRevision } else { '' })
      recordedRevision = $recordedRevision
      # The identity returned is the session that was observed, not the label the
      # caller asked about, so a reader cannot mistake an expectation for evidence.
      identity         = $(if ($observation -and $observation.proved) { $observation.state } else { $null })
      lastConfirmedThemeRevision = [string]$recordedRevision
      observedAtUtc    = (& $Dependencies.NowUtc)
      reportPath       = $reportPath
      problems         = $problems
      exitCode         = $exit
    }
  }.GetNewClosure()
  return [pscustomobject]@{
    ReadSnapshot = {
      param($Context)
      $preference = Read-ZCodeAppearancePreferences -StateRoot $stateRootValue
      $observation = & $Dependencies.ObserveSession $stateRootValue
      $state = $observation.state
      # A state file on disk is not a live session, and a live session is not a
      # confirmed appearance: only the two together make 'managed'. Anything the
      # observation cannot prove is reported as stopped or unknown and never
      # confirmed, so a dead root or a foreign port cannot inherit trust.
      $session = 'stopped'
      $confirmed = $false
      $appearance = 'native'
      if (-not $state) {
        if ($preference.status -eq 'valid') { $appearance = [string]$preference.preference.appearance }
      }
      elseif (-not $observation.proved) {
        $session = 'unknown'
        $appearance = 'pending'
      }
      elseif ([bool]$state.paused) {
        # A paused session is native by contract only when nothing is armed and no
        # revision survives in it; otherwise the reading is incomplete, not native.
        if ([int]$state.watchPid -eq 0 -and -not [string]$state.themeVersion) { $appearance = 'native' }
        else { $appearance = 'pending' }
        if ($preference.status -eq 'valid') {
          $session = 'stopped'
        }
      }
      else {
        # The session is real, but only Verify may call an appearance confirmed: a live
        # process and port prove ownership, not what the renderer is currently showing.
        $session = 'managed'
        $appearance = 'theme'
      }
      return [pscustomobject]@{
        preference      = $(if ($preference.status -eq 'valid') { $preference.preference } else { $null })
        themeRef        = $(if ($preference.status -eq 'valid') { $preference.preference.resumeTheme } else { $null })
        session         = $session
        appearance      = $appearance
        revision        = $(if ($state) { [string]$state.themeVersion } else { '' })
        identity        = $state
        # The controller publishes native from this snapshot; without the field the
        # previously confirmed skin revision would silently disappear on the switch.
        lastConfirmedThemeRevision = $(if ($preference.status -eq 'valid') { [string]$preference.preference.lastConfirmedThemeRevision } else { '' })
        confirmed       = $confirmed
        observedAt      = (& $Dependencies.NowUtc)
        observeReason   = [string]$observation.reason
        librarySnapshot = $null
      }
    }.GetNewClosure()
    ApplyTheme = {
      param($Context, $Request)
      $result = & $Dependencies.StartAppearance $stateRootValue ([string]$Context.ArtSourceFormat) $null
      return [pscustomobject]@{
        exitCode            = [int]$result.ExitCode
        productReportPath   = (Join-Path $stateRootValue 'last-apply-report.json')
        productReportSha256 = (Get-ZCodeAppearanceReportHash -StateRoot $stateRootValue)
      }
    }.GetNewClosure()
    Pause = {
      param($Context, $Request)
      $result = & $Dependencies.RestoreAppearance 'Pause' $stateRootValue $null
      $exitCode = [int]$result.ExitCode
      # A warm pause that leaves a watcher armed cannot be verified as native, and a
      # live watcher could bring the previous artwork back on reload. The unified
      # native contract is: paused first, this session's provable watchers stopped,
      # then no recorded pid. An unprovable watcher is reported, never killed.
      $state = Read-ZCodeDreamSkinState -StateRoot $stateRootValue
      if ($state -and ([int]$state.watchPid -ne 0)) {
        $stop = & $Dependencies.StopWatchers $state $stateRootValue
        if (-not [bool]$stop.stopped) {
          $exitCode = 1
        }
        else {
          $cleared = Set-ZCodeDreamSkinStateField -State $stop.state -Name 'watchPid' -Value 0
          $null = Write-ZCodeDreamSkinState -StateRoot $stateRootValue -State $cleared
        }
      }
      return [pscustomobject]@{ exitCode = $exitCode; productReportPath = ''; productReportSha256 = '' }
    }.GetNewClosure()
    Resume = {
      param($Context, $Request)
      $format = [string]$Context.ArtSourceFormat
      # One bridge, one lock: the reapply is a function call inside this process, never
      # a child CLI that would come back for the root lock the parent still holds.
      $reapply = {
        param($InnerRoot)
        return & $Dependencies.StartAppearance $InnerRoot $format $null
      }.GetNewClosure()
      $result = & $Dependencies.RestoreAppearance 'Resume' $stateRootValue $reapply
      return [pscustomobject]@{
        exitCode            = [int]$result.ExitCode
        productReportPath   = (Join-Path $stateRootValue 'last-apply-report.json')
        productReportSha256 = (Get-ZCodeAppearanceReportHash -StateRoot $stateRootValue)
      }
    }.GetNewClosure()
    Verify = {
      param($Context, $ExpectedAppearance, $ExpectedRevision)
      return & $runVerification $ExpectedAppearance $ExpectedRevision ([string]$Context.OperationId)
    }.GetNewClosure()
    Rollback = {
      param($Context, $Before)
      $observation = & $Dependencies.ObserveSession $stateRootValue
      if (-not $observation.proved) {
        # A session we cannot identify is a session whose appearance we must not
        # overwrite: the journal stays and the operator decides.
        return [pscustomobject]@{
          confirmed = $false; session = 'unknown'; appearance = 'pending'; themeId = $null; revision = ''
          identity = $Context.SessionIdentity; observedAtUtc = (& $Dependencies.NowUtc)
          problems = @("the roll back is refused because the live session cannot be proven: $($observation.reason)")
          exitCode = 1
        }
      }
      $target = 'native'
      if ([string]$Before.appearance -eq 'theme') { $target = 'theme' }
      $problems = @()
      $runExit = 1
      try {
        if ($target -eq 'theme') {
          # The previous appearance comes back through the same reapply the user
          # would trigger by hand; no second start flow is invented here.
          $rollbackReapply = {
            param($InnerRoot)
            return & $Dependencies.StartAppearance $InnerRoot ([string]$Context.ArtSourceFormat) $null
          }.GetNewClosure()
          $result = & $Dependencies.RestoreAppearance 'Resume' $stateRootValue $rollbackReapply
          $runExit = [int]$result.ExitCode
        }
        else {
          $runExit = [int](& $Dependencies.RestoreAppearance 'Pause' $stateRootValue $null).ExitCode
        }
      } catch {
        $problems += "the previous appearance could not be restored: $($_.Exception.Message)"
      }
      if ($runExit -ne 0) { $problems += "the restore of the previous appearance exited $runExit" }
      $expectedRevision = ''
      if ($target -eq 'theme') { $expectedRevision = [string]$Before.revision }
      $verify = & $runVerification $target $expectedRevision ([string]$Context.OperationId + '-rollback')
      # Three separate facts, all required: the restore action succeeded, nothing went
      # wrong on the way, and an independent verification agrees. A verification that
      # passes over a failed restore must never be reported as a rolled back session.
      $confirmed = (([int]$runExit -eq 0) -and (@($problems).Count -eq 0) -and [bool]$verify.confirmed)
      return [pscustomobject]@{
        confirmed     = $confirmed
        session       = $(if ($confirmed) { 'managed' } else { 'unknown' })
        appearance    = $verify.appearance
        themeId       = $null
        revision      = $verify.revision
        identity      = $Context.SessionIdentity
        observedAtUtc = $verify.observedAtUtc
        problems      = @(@($problems) + @($verify.problems))
        exitCode      = $(if ($confirmed) { 0 } else { 1 })
      }
    }.GetNewClosure()
    Launch = {
      param($Context, $InitialAppearance)
      # The same verified start, only told which appearance to arrive at. A native
      # cold start is published paused by that function; nothing here applies first
      # and pauses afterwards, which is what would flash a skin.
      $result = & $Dependencies.StartAppearance $stateRootValue '' $InitialAppearance
      return [pscustomobject]@{ exitCode = [int]$result.ExitCode }
    }.GetNewClosure()
    Full = {
      param($Context, $Request)
      $result = Invoke-ZCodeDreamSkinRestore -Mode Full -StateRoot $stateRootValue
      return [pscustomobject]@{
        exitCode       = [int]$result.exitCode
        sessionCleared = [bool]$result.stateCleared
        relaunched     = [bool]$result.relaunched
      }
    }.GetNewClosure()
    MutateLibrary = {
      param($Context, $Request)
      $library = Get-ZCodeDefaultAppearanceLibrary
      $method = if ($Request.action -eq 'import') { 'Import' } elseif ($Request.action -eq 'save') { 'Save' } else { 'Draft' }
      return $library.$method.Invoke($Context, $Request)
    }.GetNewClosure()
  }
}

function Get-ZCodeAppearanceReportHash {
  param([string]$StateRoot)
  $path = Join-Path $StateRoot 'last-apply-report.json'
  if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { return '' }
  return (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
}

function Invoke-Zds2AppearanceCli {
  param([string]$RequestFile, [string]$ResultFile)
  $requestId = ''
  $request = $null
  $stateRoot = ''
  try {
    if (-not $RequestFile -or -not $ResultFile) { throw 'INVALID_REQUEST:BOTH_PATHS_REQUIRED' }
    $text = Read-Zds2BoundedFile -Path $RequestFile
    $request = ConvertFrom-Json $text
    if ($null -eq $request -or -not $request.PSObject.Properties['requestId']) { throw 'INVALID_REQUEST:REQUEST_ID' }
    $requestId = [string]$request.requestId
    if (-not $request.PSObject.Properties['stateRoot']) { throw 'INVALID_REQUEST:STATE_ROOT' }
    $stateRoot = [string]$request.stateRoot
  } catch {
    # Only loading and parsing the request file is the caller's mistake. Anything the
    # orchestration itself raises must not be relabelled as a bad request, or a
    # product defect would arrive as a user-facing instruction to try again.
    return New-Zds2CliFailure -RequestId $requestId -ErrorCode 'INVALID_REQUEST' -Message "$($_.Exception.Message)"
  }
  try {
    return Invoke-ZCodeAppearanceOperation -StateRoot $stateRoot -Request $request `
      -Effects (New-Zds2LiveEffects -StateRoot $stateRoot)
  } catch {
    $escaped = "$($_.Exception.Message)"
    if (Test-DreamSkinImportLockBusy $escaped) {
      # The shared import lock is held by somebody else and the action never started - the
      # launch path reaches it through the store's recovery step. Answering
      # RECOVERY_PENDING here would tell the person a change is half-applied and needs a
      # backup, when nothing was written at all; the honest answer is to wait.
      return New-Zds2CliFailure -RequestId $requestId -ErrorCode 'BUSY' -Message $escaped
    }
    # The controller answers with results, not exceptions; reaching here means the
    # outcome is genuinely unknown.
    return New-Zds2CliFailure -RequestId $requestId -ErrorCode 'RECOVERY_PENDING' -Message $escaped
  }
}

function New-Zds2CliFailure {
  param([string]$RequestId, [string]$ErrorCode, [string]$Message)
  return [pscustomobject]@{
    schemaVersion = $ResultSchema
    requestId     = $RequestId
    ok            = $false
    status        = [pscustomobject]@{
      session = 'unknown'; appearance = 'pending'; themeId = $null; revision = $null
      confirmed = $false; errorCode = $ErrorCode; canResume = $false; busy = $false
    }
    data          = $null
    errorCode     = $ErrorCode
    message       = $Message
    operationId   = $null
  }
}

# Dot-sourcing must never run or exit: the gallery bridge and the tests load these
# definitions beside their own entry point.
if ($MyInvocation.InvocationName -ne '.') {
  $result = Invoke-Zds2AppearanceCli -RequestFile $RequestFile -ResultFile $ResultFile
  if ($ResultFile) {
    Write-Zds2Result -Path $ResultFile -Result $result
  }
  Write-Output ('appearance-cli ' + $(if ($result.ok) { 'ok' } else { 'rejected' }) +
    ' errorCode=' + $result.errorCode + ' detail=' + $result.message)
  exit $(if ($result.ok) { 0 } elseif ($result.errorCode -eq 'BUSY') { 4 } else { 1 })
}
